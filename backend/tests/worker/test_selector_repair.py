def test_repair_respects_budget():
    """Repair completes within timeout_ms."""
    elements = [
        {
            "tag": "button", "text": f"Button {i}", "ariaLabel": "",
            "role": "button", "id": f"btn-{i}", "name": "",
            "placeholder": "", "testId": "",
            "rect": {"x": 10, "y": 20 + i * 50, "w": 100, "h": 40},
            "index": i,
        }
        for i in range(20)
    ]

    page = _make_page(interactive_elements=elements)
    page.get_by_text.return_value = MagicMock(count=MagicMock(return_value=0))

    # No match should be found, but budget should not be exceeded
    target = TargetDescriptor(role="button", name="Nonexistent Button XYZ")
    diagnosis = _make_diagnosis()

    t0 = time.monotonic()
    result = repair_selector(page, target, diagnosis, timeout_ms=5000)
    elapsed = (time.monotonic() - t0) * 1000

    # Should complete well within budget (no real waits in mocks)
    assert elapsed < 3000
    assert not result.repaired


