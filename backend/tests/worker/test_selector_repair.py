def test_selector_repair_visibility_checked():
    """Pipeline rejects candidate with visibility=0.0 and low composite."""
    elements = [
        {
            "tag": "button", "text": "Submit Forms", "ariaLabel": "",
            "role": "button", "id": "hidden-btn", "name": "",
            "placeholder": "", "testId": "",
            "rect": {"x": 10, "y": 20, "w": 100, "h": 40},
            "index": 0,
        },
    ]

    page = _make_page(interactive_elements=elements)
    mock_locator = MagicMock()
    mock_locator.count.return_value = 1
    page.locator.return_value = mock_locator
    page.get_by_text.return_value = MagicMock(count=MagicMock(return_value=0))

    target = TargetDescriptor(role="button", name="Submit Form")
    diagnosis = _make_diagnosis()

    # Pipeline returns low composite because visibility=0.0
    hidden_candidate = CandidateScore(
        locator=mock_locator,
        strategy=SelectorStrategy.CSS,
        params={"selector": "repair:text_similarity"},
        composite=0.25,
        visibility_score=0.0,
    )
    with patch("app.worker.healing.selector_repair.score_candidates",
               return_value=[hidden_candidate]):
        result = repair_selector(page, target, diagnosis)

    assert not result.repaired
