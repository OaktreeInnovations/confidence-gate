"""Tests for Selector Repair Engine (Healing Layer 1).

Validates 5 repair strategies:
1. Text similarity — fuzzy match textContent
2. Aria-label similarity — fuzzy match aria-label
3. Label association — follow label[for]
4. Interactive ancestor — walk up to interactive parent
5. Element type match — same role/tag near position

All strategies pre-filter via fuzzy matching, then validate through
score_candidates() pipeline.
"""

import time
from unittest.mock import MagicMock, patch

from app.worker.healing.selector_repair import (
    RepairResult,
    _similarity_ratio,
    _looks_autogenerated,
    repair_selector,
)
from app.worker.intent_schema import TargetDescriptor
from app.worker.recovery.diagnosis import FailureDiagnosis, FailureType
from app.worker.selector_engine.scoring import CandidateScore
from app.worker.selector_resilience import SelectorStrategy


def _make_diagnosis(failure_type=FailureType.ELEMENT_NOT_FOUND):
    return FailureDiagnosis(
        failure_type=failure_type,
        root_cause="Element not found",
        is_recoverable=True,
    )


def _make_page(interactive_elements=None, label_elements=None):
    """Create a mock page with controllable evaluate() responses."""
    page = MagicMock()

    def evaluate_side_effect(js, *args, **kwargs):
        if "querySelectorAll(selectors" in js:
            # Interactive elements JS
            return interactive_elements or []
        if "querySelectorAll('label')" in js:
            return label_elements or []
        return None

    page.evaluate.side_effect = evaluate_side_effect
    return page


def _mock_score_candidates(composite=0.7):
    """Create a mock score_candidates return value with given composite."""
    mock_locator = MagicMock()
    return [CandidateScore(
        locator=mock_locator,
        strategy=SelectorStrategy.CSS,
        params={"selector": "repair:test"},
        composite=composite,
    )]


# --- Utility tests ---


def test_similarity_ratio_exact_match():
    """Exact strings return 1.0."""
    assert _similarity_ratio("submit", "submit") == 1.0


def test_similarity_ratio_partial_match():
    """Similar strings return high ratio."""
    ratio = _similarity_ratio("submit form", "submit")
    assert 0.5 < ratio < 1.0


def test_similarity_ratio_empty():
    """Empty string returns 0.0."""
    assert _similarity_ratio("", "submit") == 0.0
    assert _similarity_ratio("submit", "") == 0.0


def test_looks_autogenerated():
    """Auto-generated IDs detected correctly."""
    assert _looks_autogenerated(":r0:")
    assert _looks_autogenerated("react-select-3-option-0")
    assert _looks_autogenerated("btn-a3f2c1b0")
    assert not _looks_autogenerated("submit-btn")
    assert not _looks_autogenerated("email-input")


# --- Strategy 1: Text similarity ---


def test_text_similarity_finds_renamed_button():
    """Element with similar text content is found via fuzzy match.

    Simulates a button renamed from "Submit Form" to "Submit Forms" — high
    similarity ratio (>0.95) triggers repair. Pipeline validates the candidate.
    """
    elements = [
        {
            "tag": "button", "text": "Submit Forms", "ariaLabel": "",
            "role": "button", "id": "submit-btn", "name": "",
            "placeholder": "", "testId": "",
            "rect": {"x": 10, "y": 20, "w": 100, "h": 40},
            "index": 0,
        },
    ]

    page = _make_page(interactive_elements=elements)
    # Mock the locator returned by page.locator("#submit-btn")
    mock_locator = MagicMock()
    mock_locator.count.return_value = 1
    page.locator.return_value = mock_locator

    target = TargetDescriptor(role="button", name="Submit Form")
    diagnosis = _make_diagnosis()

    with patch("app.worker.healing.selector_repair.score_candidates",
               return_value=_mock_score_candidates(0.75)):
        result = repair_selector(page, target, diagnosis)

    assert result.repaired
    assert result.strategy_used == "text_similarity"
    assert result.confidence >= 0.45
    assert result.locator is not None


